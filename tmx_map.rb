#loads a Tmx file and converts it into a 2d array.
def get_map(dir)
    map = Tmx.load(dir) 
    layer = map.layers[0]
    map_arr = []
    row = []
    count = 0
    while layer.data[0] != nil
        if count == layer.width
            count = 0
            map_arr << row
            row = []
        else
            row << layer.data[0]
            layer.data.delete_at(0)
            count += 1
        end
    end
    map_arr << row
    p map_arr
    return map_arr
end 

def define_tiles()
    tile_info = get_tile_info()
    tile_info.each_key do |id|
        x = tile_info[id]["x"]
        y = tile_info[id]["y"]
        $tileset.define_tile(id, x, y)
    end
    p "tiles are defined"
end

def get_tile_info()
    tile_info = {}
    tile_ids = get_tile_ids()
    tile_positions = get_tile_positions()
    i = 0
    while i < tile_ids.length
        tile_id = tile_ids[i]
        tile_pos = tile_positions[i]
        x = tile_pos["x"]
        y = tile_pos["y"]
        tile_info[tile_id] = {"x" => x, "y" => y}
        i += 1
    end
    return tile_info
end

def get_tile_positions()
    box_size = 16
    positions = []
    width = 256
    height = 192
    y = 0
    while y < height / box_size
        x = 0
        while x < width / box_size
            positions << {"x" => x, "y" => y}
            x += 1
        end
        y += 1
    end
    return positions
end

def get_tile_ids()
    values = []
    id = 1
    width = 256
    height = 192
    y = 0
    while y < height
        x = 0
        while x < width
            values << id
            id += 1
            x += 16
        end
        y += 16
    end
    return values
end

